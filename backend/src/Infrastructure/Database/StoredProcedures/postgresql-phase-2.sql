-- 8. usp_Permission_ListForAdmin
CREATE OR REPLACE FUNCTION public.usp_permission_listforadmin(p_actoruserid uuid,p_targetuserid uuid)
RETURNS SETOF jsonb LANGUAGE plpgsql STABLE AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM public.app_user WHERE user_id=p_actoruserid AND is_active AND role='Administrador') THEN RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='Forbidden'; END IF;
 IF NOT EXISTS(SELECT 1 FROM public.app_user WHERE user_id=p_targetuserid AND role='Viewer') THEN RAISE EXCEPTION USING ERRCODE='P0002',MESSAGE='Viewer not found'; END IF;
