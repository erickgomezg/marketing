-- 9. usp_Permission_SaveForViewer
CREATE OR REPLACE FUNCTION public.usp_permission_saveforviewer(p_actoruserid uuid,p_targetuserid uuid,p_assignments jsonb)
RETURNS SETOF jsonb LANGUAGE plpgsql AS $$
DECLARE v_item jsonb; v_bid uuid; v_pid integer; v_active boolean; v_count integer:=0;
BEGIN
 IF NOT EXISTS(SELECT 1 FROM public.app_user WHERE user_id=p_actoruserid AND is_active AND role='Administrador') THEN RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='Forbidden'; END IF;
 IF NOT EXISTS(SELECT 1 FROM public.app_user WHERE user_id=p_targetuserid AND role='Viewer') THEN RAISE EXCEPTION USING ERRCODE='P0002',MESSAGE='Viewer not found'; END IF;
 IF jsonb_typeof(p_assignments)<>'array' THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Invalid assignments'; END IF;
 IF EXISTS(SELECT 1 FROM jsonb_array_elements(p_assignments) e GROUP BY (e->>'businessId'),(e->>'socialPlatformId') HAVING count(*)>1) THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Duplicate assignments'; END IF;
 FOR v_item IN SELECT value FROM jsonb_array_elements(p_assignments) LOOP
   v_bid:=(v_item->>'businessId')::uuid; v_pid:=(v_item->>'socialPlatformId')::integer; v_active:=coalesce((v_item->>'isActive')::boolean,false);
   IF NOT EXISTS(SELECT 1 FROM public.business b JOIN public.social_platform s ON s.social_platform_id=v_pid WHERE b.business_id=v_bid AND b.status='Active' AND s.is_active) THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Unknown business or platform'; END IF;
   IF v_active THEN v_count:=v_count+1; END IF;
 END LOOP;
 IF v_count=0 THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Viewer requires at least one active permission'; END IF;
 UPDATE public.user_business_platform_permission p SET is_active=coalesce((SELECT (e->>'isActive')::boolean FROM jsonb_array_elements(p_assignments) e WHERE (e->>'businessId')::uuid=p.business_id AND (e->>'socialPlatformId')::integer=p.social_platform_id LIMIT 1),false)
 WHERE p.user_id=p_targetuserid;
 FOR v_item IN SELECT value FROM jsonb_array_elements(p_assignments) WHERE coalesce((value->>'isActive')::boolean,false) LOOP
   INSERT INTO public.user_business_platform_permission(permission_id,user_id,business_id,social_platform_id,is_active,created_by)
   VALUES(gen_random_uuid(),p_targetuserid,(v_item->>'businessId')::uuid,(v_item->>'socialPlatformId')::integer,true,p_actoruserid)
   ON CONFLICT(user_id,business_id,social_platform_id) DO UPDATE SET is_active=true;
 END LOOP;
 INSERT INTO public.audit_log(actor_user_id,target_user_id,action,details) VALUES(p_actoruserid,p_targetuserid,'user.permissions_changed','Active assignments='||v_count);
 RETURN;
END $$;

-- 10. usp_SocialAccount_ListAuthorized
CREATE OR REPLACE FUNCTION public.usp_socialaccount_listauthorized(p_userid uuid,p_businessid uuid DEFAULT NULL,p_socialplatformid integer DEFAULT NULL)
RETURNS SETOF jsonb LANGUAGE plpgsql STABLE AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM public.app_user WHERE user_id=p_userid AND is_active) THEN RAISE EXCEPTION USING ERRCODE='28000',MESSAGE='Unauthorized'; END IF;
 RETURN QUERY SELECT jsonb_build_object('SocialAccountId',a.social_account_id,'BusinessId',a.business_id,'BusinessName',b.name,'SocialPlatformId',a.social_platform_id,'PlatformCode',p.code,'ExternalAccountId',a.external_account_id,'Name',a.name,'Status',a.status,'ExternalConnectionId',a.external_connection_id)
 FROM public.social_account a JOIN public.business b ON b.business_id=a.business_id JOIN public.social_platform p ON p.social_platform_id=a.social_platform_id
 JOIN public.app_user u ON u.user_id=p_userid
 WHERE a.status='Connected' AND b.status='Active' AND (p_businessid IS NULL OR a.business_id=p_businessid) AND (p_socialplatformid IS NULL OR a.social_platform_id=p_socialplatformid)
 AND (u.role='Administrador' OR EXISTS(SELECT 1 FROM public.user_business_platform_permission x WHERE x.user_id=p_userid AND x.business_id=a.business_id AND x.social_platform_id=a.social_platform_id AND x.is_active));
END $$;

