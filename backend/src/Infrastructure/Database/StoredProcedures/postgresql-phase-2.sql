-- 12. usp_User: list/get/assignment_options/create/update/role actions
CREATE OR REPLACE FUNCTION public.usp_user(
 p_accion varchar(20),p_actoruserid uuid DEFAULT NULL,p_targetuserid uuid DEFAULT NULL,
 p_email varchar(320) DEFAULT NULL,p_displayname varchar(200) DEFAULT NULL,p_role varchar(20) DEFAULT NULL,p_isactive boolean DEFAULT NULL,
 p_assignments jsonb DEFAULT NULL,p_tokenhash bytea DEFAULT NULL,p_expiresat timestamptz DEFAULT NULL,p_payloadencrypted text DEFAULT NULL)
RETURNS SETOF jsonb LANGUAGE plpgsql AS $$
DECLARE v_oldrole varchar(20); v_a jsonb; v_bid uuid; v_pid integer;
BEGIN
 IF p_accion IN ('list','get','assignment_options') THEN
   IF NOT EXISTS(SELECT 1 FROM public.app_user WHERE user_id=p_actoruserid AND is_active AND role='Administrador') THEN RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='Forbidden'; END IF;
   IF p_accion='assignment_options' THEN
     RETURN QUERY SELECT jsonb_build_object('BusinessId',b.business_id,'BusinessName',b.name,'SocialPlatformId',s.social_platform_id,'PlatformCode',s.code,'PlatformName',s.name) FROM public.business b CROSS JOIN public.social_platform s WHERE b.status='Active' AND s.is_active ORDER BY b.name,s.name; RETURN;
   END IF;
   RETURN QUERY SELECT jsonb_build_object('UserId',u.user_id,'DisplayName',u.display_name,'Email',u.email,'Role',u.role,'IsActive',u.is_active,'CreatedAt',u.created_at,'ActivatedAt',u.activated_at,
    'InvitationStatus',CASE WHEN u.is_active THEN 'Active' WHEN u.activated_at IS NULL AND EXISTS(SELECT 1 FROM public.user_invitation i WHERE i.user_id=u.user_id AND i.accepted_at IS NULL AND i.revoked_at IS NULL AND i.expires_at>now()) THEN 'Invited' WHEN u.activated_at IS NULL THEN 'InvitationRequired' ELSE 'Inactive' END)
   FROM public.app_user u WHERE p_accion='list' OR u.user_id=p_targetuserid ORDER BY u.display_name; RETURN;
 END IF;
 IF p_accion='create' THEN
   IF p_email IS NULL OR p_displayname IS NULL OR p_role NOT IN ('Administrador','Viewer') THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Invalid user fields'; END IF;
   IF p_tokenhash IS NULL OR octet_length(p_tokenhash)<>32 OR p_expiresat<=now() OR p_payloadencrypted IS NULL THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Invalid invitation data'; END IF;
   IF p_role='Viewer' AND (jsonb_typeof(p_assignments)<>'array' OR jsonb_array_length(p_assignments)=0) THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Viewer requires permissions'; END IF;
   IF NOT EXISTS(SELECT 1 FROM public.app_user WHERE user_id=p_actoruserid AND is_active AND role='Administrador') THEN RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='Forbidden'; END IF;
   IF EXISTS(SELECT 1 FROM public.app_user WHERE email=lower(btrim(p_email))) THEN RAISE EXCEPTION USING ERRCODE='23505',MESSAGE='Duplicate email'; END IF;
   INSERT INTO public.app_user(user_id,email,display_name,role,is_active) VALUES(p_targetuserid,lower(btrim(p_email)),btrim(p_displayname),p_role,false);
   IF p_role='Viewer' THEN
     FOR v_a IN SELECT value FROM jsonb_array_elements(p_assignments) LOOP
       v_bid:=(v_a->>'businessId')::uuid; v_pid:=(v_a->>'socialPlatformId')::integer;
       IF NOT EXISTS(SELECT 1 FROM public.business b JOIN public.social_platform s ON s.social_platform_id=v_pid WHERE b.business_id=v_bid AND b.status='Active' AND s.is_active) THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Unknown business or platform'; END IF;
       INSERT INTO public.user_business_platform_permission(permission_id,user_id,business_id,social_platform_id,created_by) VALUES(gen_random_uuid(),p_targetuserid,v_bid,v_pid,p_actoruserid);
     END LOOP;
   END IF;
   INSERT INTO public.user_invitation(user_id,token_hash,expires_at) VALUES(p_targetuserid,p_tokenhash,p_expiresat);
   INSERT INTO public.email_outbox(user_id,message_type,payload_encrypted) VALUES(p_targetuserid,'invitation',p_payloadencrypted);
   INSERT INTO public.audit_log(actor_user_id,target_user_id,action,details) VALUES(p_actoruserid,p_targetuserid,'user.created','Role='||p_role);
   RETURN QUERY SELECT jsonb_build_object('UserId',user_id,'Email',email,'DisplayName',display_name,'Role',role,'IsActive',is_active,'CreatedAt',created_at,'ActivatedAt',activated_at) FROM public.app_user WHERE user_id=p_targetuserid; RETURN;
 END IF;
 IF p_accion='update' THEN
   IF p_email IS NULL OR p_displayname IS NULL THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Invalid user fields'; END IF;
   IF NOT EXISTS(SELECT 1 FROM public.app_user WHERE user_id=p_actoruserid AND is_active AND role='Administrador') THEN RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='Forbidden'; END IF;
   UPDATE public.app_user SET email=lower(btrim(p_email)),display_name=btrim(p_displayname) WHERE user_id=p_targetuserid;
   IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002',MESSAGE='User not found'; END IF;
   INSERT INTO public.audit_log(actor_user_id,target_user_id,action,details) VALUES(p_actoruserid,p_targetuserid,'user.updated','Profile changed');
   RETURN QUERY SELECT jsonb_build_object('UserId',user_id,'Email',email,'DisplayName',display_name,'Role',role,'IsActive',is_active,'CreatedAt',created_at,'ActivatedAt',activated_at) FROM public.app_user WHERE user_id=p_targetuserid; RETURN;
 END IF;
 IF p_accion='role' THEN
   IF p_role NOT IN ('Administrador','Viewer') THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Invalid role'; END IF;
   PERFORM pg_advisory_xact_lock(hashtext('AI_MARKETING_MANAGER:administrator-lifecycle'));
   IF NOT EXISTS(SELECT 1 FROM public.app_user WHERE user_id=p_actoruserid AND is_active AND role='Administrador') THEN RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='Forbidden'; END IF;
   SELECT role INTO v_oldrole FROM public.app_user WHERE user_id=p_targetuserid FOR UPDATE;
   IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002',MESSAGE='Active user not found'; END IF;
   IF v_oldrole='Administrador' AND p_role='Viewer' THEN
     IF EXISTS(SELECT 1 FROM public.app_user WHERE user_id=p_targetuserid AND is_active) AND (SELECT count(*) FROM public.app_user WHERE role='Administrador' AND is_active)<=1 THEN RAISE EXCEPTION USING ERRCODE='P0001',MESSAGE='Cannot demote the last active administrator'; END IF;
     IF jsonb_typeof(p_assignments)<>'array' OR jsonb_array_length(p_assignments)=0 THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Viewer requires permissions'; END IF;
     UPDATE public.user_business_platform_permission SET is_active=false WHERE user_id=p_targetuserid;
     FOR v_a IN SELECT value FROM jsonb_array_elements(p_assignments) LOOP
       v_bid:=(v_a->>'businessId')::uuid; v_pid:=(v_a->>'socialPlatformId')::integer;
       IF NOT EXISTS(SELECT 1 FROM public.business b JOIN public.social_platform s ON s.social_platform_id=v_pid WHERE b.business_id=v_bid AND b.status='Active' AND s.is_active) THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Unknown business or platform'; END IF;
       INSERT INTO public.user_business_platform_permission(permission_id,user_id,business_id,social_platform_id,is_active,created_by) VALUES(gen_random_uuid(),p_targetuserid,v_bid,v_pid,true,p_actoruserid)
       ON CONFLICT(user_id,business_id,social_platform_id) DO UPDATE SET is_active=true;
     END LOOP;
   END IF;
   IF v_oldrole='Viewer' AND p_role='Administrador' THEN UPDATE public.user_business_platform_permission SET is_active=false WHERE user_id=p_targetuserid; END IF;
   UPDATE public.app_user SET role=p_role,auth_version=auth_version+1 WHERE user_id=p_targetuserid;
   UPDATE public.auth_session SET revoked_at=now() WHERE user_id=p_targetuserid AND revoked_at IS NULL;
   INSERT INTO public.audit_log(actor_user_id,target_user_id,action,details) VALUES(p_actoruserid,p_targetuserid,'user.role_changed',v_oldrole||'->'||p_role);
   RETURN;
 END IF;
 RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Unknown user action';
END $$;

-- 13. usp_Invitation
CREATE OR REPLACE FUNCTION public.usp_invitation(p_accion varchar(20),p_actoruserid uuid DEFAULT NULL,p_targetuserid uuid DEFAULT NULL,
 p_tokenhash bytea DEFAULT NULL,p_expiresat timestamptz DEFAULT NULL,p_payloadencrypted text DEFAULT NULL,p_passwordhash varchar(255) DEFAULT NULL)
RETURNS SETOF jsonb LANGUAGE plpgsql AS $$
DECLARE v_userid uuid;
BEGIN
 IF p_accion='validate' THEN
   RETURN QUERY SELECT jsonb_build_object('UserId',u.user_id,'Email',u.email,'DisplayName',u.display_name,'Role',u.role,'ExpiresAt',i.expires_at)
   FROM public.user_invitation i JOIN public.app_user u ON u.user_id=i.user_id
   WHERE i.token_hash=p_tokenhash AND i.accepted_at IS NULL AND i.revoked_at IS NULL AND i.expires_at>now() AND NOT u.is_active AND u.activated_at IS NULL LIMIT 1; RETURN;
 END IF;
 IF p_accion='accept' THEN
   IF p_passwordhash IS NULL OR p_tokenhash IS NULL THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Invalid invitation'; END IF;
   SELECT i.user_id INTO v_userid FROM public.user_invitation i JOIN public.app_user u ON u.user_id=i.user_id
   WHERE i.token_hash=p_tokenhash AND i.accepted_at IS NULL AND i.revoked_at IS NULL AND i.expires_at>now() AND NOT u.is_active AND u.activated_at IS NULL FOR UPDATE OF i,u;
   IF v_userid IS NULL THEN RAISE EXCEPTION USING ERRCODE='P0001',MESSAGE='Invitation is invalid or expired'; END IF;
   UPDATE public.app_user SET password_hash=p_passwordhash,is_active=true,activated_at=now(),auth_version=auth_version+1 WHERE user_id=v_userid;
   UPDATE public.user_invitation SET accepted_at=now() WHERE token_hash=p_tokenhash;
   UPDATE public.user_invitation SET revoked_at=now() WHERE user_id=v_userid AND token_hash<>p_tokenhash AND accepted_at IS NULL AND revoked_at IS NULL;
   INSERT INTO public.audit_log(target_user_id,action,details) VALUES(v_userid,'invitation.accepted','Account activated'); RETURN;
 END IF;
 IF p_accion IN ('resend','revoke') THEN
   IF NOT EXISTS(SELECT 1 FROM public.app_user WHERE user_id=p_actoruserid AND is_active AND role='Administrador') THEN RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='Forbidden'; END IF;
   IF NOT EXISTS(SELECT 1 FROM public.app_user WHERE user_id=p_targetuserid AND NOT is_active AND activated_at IS NULL) THEN RAISE EXCEPTION USING ERRCODE='P0002',MESSAGE='Pending user not found'; END IF;
   UPDATE public.user_invitation SET revoked_at=now() WHERE user_id=p_targetuserid AND accepted_at IS NULL AND revoked_at IS NULL;
   IF p_accion='resend' THEN
     IF p_tokenhash IS NULL OR octet_length(p_tokenhash)<>32 OR p_expiresat<=now() OR p_payloadencrypted IS NULL THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Invalid invitation data'; END IF;
     INSERT INTO public.user_invitation(user_id,token_hash,expires_at) VALUES(p_targetuserid,p_tokenhash,p_expiresat);
     INSERT INTO public.email_outbox(user_id,message_type,payload_encrypted) VALUES(p_targetuserid,'invitation',p_payloadencrypted);
   END IF;
   INSERT INTO public.audit_log(actor_user_id,target_user_id,action) VALUES(p_actoruserid,p_targetuserid,'invitation.'||p_accion); RETURN;
 END IF;
 RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Unknown invitation action';
END $$;

-- 14. usp_PasswordReset
CREATE OR REPLACE FUNCTION public.usp_passwordreset(p_accion varchar(20),p_email varchar(320) DEFAULT NULL,p_tokenhash bytea DEFAULT NULL,
 p_expiresat timestamptz DEFAULT NULL,p_payloadencrypted text DEFAULT NULL,p_passwordhash varchar(255) DEFAULT NULL)
RETURNS SETOF jsonb LANGUAGE plpgsql AS $$
DECLARE v_userid uuid;
BEGIN
 IF p_accion='request' THEN
   SELECT user_id INTO v_userid FROM public.app_user WHERE email=lower(btrim(p_email)) AND is_active AND password_hash IS NOT NULL FOR UPDATE;
   IF v_userid IS NOT NULL THEN
     UPDATE public.password_reset_token SET revoked_at=now() WHERE user_id=v_userid AND used_at IS NULL AND revoked_at IS NULL;
     IF p_tokenhash IS NOT NULL AND octet_length(p_tokenhash)=32 AND p_expiresat>now() AND p_payloadencrypted IS NOT NULL THEN
       INSERT INTO public.password_reset_token(user_id,token_hash,expires_at) VALUES(v_userid,p_tokenhash,p_expiresat);
       INSERT INTO public.email_outbox(user_id,message_type,payload_encrypted) VALUES(v_userid,'password_reset',p_payloadencrypted);
     END IF;
   END IF;
   RETURN;
 END IF;
 IF p_accion='reset' THEN
   SELECT user_id INTO v_userid FROM public.password_reset_token WHERE token_hash=p_tokenhash AND used_at IS NULL AND revoked_at IS NULL AND expires_at>now() FOR UPDATE;
   IF v_userid IS NULL THEN RAISE EXCEPTION USING ERRCODE='P0001',MESSAGE='Reset token is invalid or expired'; END IF;
   UPDATE public.app_user SET password_hash=p_passwordhash,auth_version=auth_version+1 WHERE user_id=v_userid AND is_active;
   IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0001',MESSAGE='Reset token is invalid or expired'; END IF;
   UPDATE public.password_reset_token SET used_at=now() WHERE token_hash=p_tokenhash;
   UPDATE public.password_reset_token SET revoked_at=now() WHERE user_id=v_userid AND token_hash<>p_tokenhash AND used_at IS NULL AND revoked_at IS NULL;
   UPDATE public.auth_session SET revoked_at=now() WHERE user_id=v_userid AND revoked_at IS NULL;
   INSERT INTO public.audit_log(target_user_id,action,details) VALUES(v_userid,'password.reset','Sessions revoked by AuthVersion increment'); RETURN;
 END IF;
 RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Unknown password reset action';
END $$;

-- 15. usp_EmailOutbox
CREATE OR REPLACE FUNCTION public.usp_emailoutbox(p_accion varchar(20),p_outboxid uuid DEFAULT NULL,p_sent boolean DEFAULT NULL,p_errorcode varchar(80) DEFAULT NULL)
RETURNS SETOF jsonb LANGUAGE plpgsql AS $$
DECLARE r record;
BEGIN
 IF p_accion='claim' THEN
   FOR r IN
     SELECT * FROM public.email_outbox
     WHERE ((status IN ('Pending','Failed') AND next_attempt_at<=now() AND attempt_count<8)
       OR (status='Sending' AND last_attempt_at<now()-interval '10 minutes'))
     ORDER BY created_at FOR UPDATE SKIP LOCKED LIMIT 10
   LOOP
     UPDATE public.email_outbox SET status='Sending',last_attempt_at=now() WHERE outbox_id=r.outbox_id;
     RETURN NEXT jsonb_build_object('OutboxId',r.outbox_id,'UserId',r.user_id,'MessageType',r.message_type,'PayloadEncrypted',r.payload_encrypted);
   END LOOP;
   RETURN;
 END IF;
 IF p_accion='sent' THEN
   UPDATE public.email_outbox SET status='Sent',sent_at=now(),attempt_count=attempt_count+1,last_error_code=NULL WHERE outbox_id=p_outboxid; RETURN;
 END IF;
 IF p_accion='failed' THEN
   UPDATE public.email_outbox SET attempt_count=attempt_count+1,status=CASE WHEN attempt_count+1>=8 THEN 'Failed' ELSE 'Pending' END,
     next_attempt_at=now()+make_interval(mins=>CASE WHEN attempt_count<1 THEN 1 WHEN attempt_count<4 THEN 5 ELSE 30 END),last_error_code=p_errorcode WHERE outbox_id=p_outboxid; RETURN;
 END IF;
 RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Unknown outbox action';
END $$;

-- 16. usp_Auth_Session
CREATE OR REPLACE FUNCTION public.usp_auth_session(p_accion varchar(20),p_userid uuid DEFAULT NULL,p_sessionid uuid DEFAULT NULL,
 p_tokenhash bytea DEFAULT NULL,p_newtokenhash bytea DEFAULT NULL,p_expiresat timestamptz DEFAULT NULL)
RETURNS SETOF jsonb LANGUAGE plpgsql AS $$
DECLARE v_session uuid; v_user uuid; v_current bytea; v_auth integer; v_email varchar(320); v_name varchar(200); v_role varchar(20);
BEGIN
 IF p_accion='create' THEN
   IF p_userid IS NULL OR p_sessionid IS NULL OR p_tokenhash IS NULL OR octet_length(p_tokenhash)<>32 OR p_expiresat<=now() THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Invalid session data'; END IF;
   IF NOT EXISTS(SELECT 1 FROM public.app_user WHERE user_id=p_userid AND is_active) THEN RAISE EXCEPTION USING ERRCODE='P0001',MESSAGE='User is inactive'; END IF;
   INSERT INTO public.auth_session(session_id,user_id,refresh_token_hash,expires_at) VALUES(p_sessionid,p_userid,p_tokenhash,p_expiresat);
   RETURN NEXT jsonb_build_object('SessionId',p_sessionid,'UserId',p_userid); RETURN;
 END IF;
 IF p_accion='rotate' THEN
   IF p_tokenhash IS NULL OR octet_length(p_tokenhash)<>32 OR p_newtokenhash IS NULL OR octet_length(p_newtokenhash)<>32 OR p_expiresat<=now() THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Invalid refresh token data'; END IF;
   SELECT session_id,user_id,refresh_token_hash INTO v_session,v_user,v_current FROM public.auth_session WHERE refresh_token_hash=p_tokenhash AND revoked_at IS NULL AND expires_at>now() FOR UPDATE;
   IF v_session IS NULL THEN
     SELECT session_id INTO v_session FROM public.auth_session_token_history WHERE token_hash=p_tokenhash FOR UPDATE;
     IF v_session IS NOT NULL THEN
       SELECT user_id INTO v_user FROM public.auth_session WHERE session_id=v_session;
       UPDATE public.auth_session SET revoked_at=now() WHERE session_id=v_session AND revoked_at IS NULL;
       INSERT INTO public.audit_log(target_user_id,action,details) VALUES(v_user,'session.refresh_reuse_detected','Session revoked after reuse of a rotated refresh token');
       RETURN NEXT jsonb_build_object('ErrorCode','REFRESH_TOKEN_REUSE');
       RETURN;
     END IF;
     RAISE EXCEPTION USING ERRCODE='P0001',MESSAGE='Refresh token is invalid or expired';
   END IF;
   IF EXISTS(SELECT 1 FROM public.auth_session_token_history WHERE token_hash=p_newtokenhash) OR EXISTS(SELECT 1 FROM public.auth_session WHERE refresh_token_hash=p_newtokenhash) THEN RAISE EXCEPTION USING ERRCODE='23505',MESSAGE='Refresh token collision'; END IF;
   INSERT INTO public.auth_session_token_history(token_hash,session_id) VALUES(v_current,v_session);
   UPDATE public.auth_session SET refresh_token_hash=p_newtokenhash,expires_at=p_expiresat,last_used_at=now() WHERE session_id=v_session;
   SELECT auth_version,email,display_name,role INTO v_auth,v_email,v_name,v_role FROM public.app_user WHERE user_id=v_user AND is_active;
   IF FOUND THEN RETURN NEXT jsonb_build_object('SessionId',v_session,'UserId',v_user,'AuthVersion',v_auth,'Email',v_email,'DisplayName',v_name,'Role',v_role); END IF;
   RETURN;
 END IF;
 IF p_accion='revoke' THEN UPDATE public.auth_session SET revoked_at=now() WHERE refresh_token_hash=p_tokenhash AND revoked_at IS NULL; RETURN; END IF;
 IF p_accion='revoke_all' THEN UPDATE public.auth_session SET revoked_at=now() WHERE user_id=p_userid AND revoked_at IS NULL; RETURN; END IF;
 RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Unknown session action';
END $$;

