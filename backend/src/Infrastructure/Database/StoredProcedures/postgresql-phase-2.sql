-- 6. usp_User_SetActive
CREATE OR REPLACE FUNCTION public.usp_user_setactive(p_actoruserid uuid,p_targetuserid uuid,p_isactive boolean)
RETURNS SETOF jsonb LANGUAGE plpgsql AS $$
DECLARE v_role varchar(20); v_activated timestamptz; v_hash varchar(255);
BEGIN
 PERFORM pg_advisory_xact_lock(hashtext('AI_MARKETING_MANAGER:administrator-lifecycle'));
 IF NOT EXISTS(SELECT 1 FROM public.app_user WHERE user_id=p_actoruserid AND is_active AND role='Administrador') THEN RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='Forbidden'; END IF;
 SELECT role,activated_at,password_hash INTO v_role,v_activated,v_hash FROM public.app_user WHERE user_id=p_targetuserid FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002',MESSAGE='User not found'; END IF;
 IF p_isactive AND (v_hash IS NULL OR v_activated IS NULL) THEN RAISE EXCEPTION USING ERRCODE='P0001',MESSAGE='Pending user must accept invitation before activation'; END IF;
 IF NOT p_isactive AND v_role='Administrador' AND (SELECT count(*) FROM public.app_user WHERE role='Administrador' AND is_active)<=1 THEN RAISE EXCEPTION USING ERRCODE='P0001',MESSAGE='Cannot deactivate the last active administrator'; END IF;
 UPDATE public.app_user SET is_active=p_isactive,auth_version=auth_version+1 WHERE user_id=p_targetuserid;
 IF NOT p_isactive THEN UPDATE public.auth_session SET revoked_at=now() WHERE user_id=p_targetuserid AND revoked_at IS NULL; END IF;
 INSERT INTO public.audit_log(actor_user_id,target_user_id,action,details) VALUES(p_actoruserid,p_targetuserid,'user.active','IsActive='||p_isactive::text);
 RETURN;
END $$;

