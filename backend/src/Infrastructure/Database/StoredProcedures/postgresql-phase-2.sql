 FROM public.app_user WHERE email=p_email LIMIT 1
$$;

-- 3. usp_Auth_BootstrapAdministrator (serialize first-admin creation with transaction advisory lock)
CREATE OR REPLACE FUNCTION public.usp_auth_bootstrapadministrator(p_email varchar(320),p_displayname varchar(200),p_passwordhash varchar(255))
RETURNS SETOF jsonb LANGUAGE plpgsql AS $$
DECLARE v_created boolean := false;
BEGIN
 PERFORM pg_advisory_xact_lock(hashtext('AI_MARKETING_MANAGER:first-administrator'));
 IF NOT EXISTS(SELECT 1 FROM public.app_user WHERE role='Administrador') THEN
   IF EXISTS(SELECT 1 FROM public.app_user WHERE email=p_email) THEN
     RAISE EXCEPTION USING ERRCODE='P0001',MESSAGE='Bootstrap email already belongs to a non-administrator';
   END IF;
   INSERT INTO public.app_user(user_id,email,display_name,role,is_active,password_hash,activated_at)
   VALUES(gen_random_uuid(),p_email,p_displayname,'Administrador',true,p_passwordhash,now());
   v_created := true;
 END IF;
 RETURN NEXT jsonb_build_object('Created',v_created);
END $$;

