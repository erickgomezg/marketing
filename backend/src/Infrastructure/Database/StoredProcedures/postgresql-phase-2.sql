-- PostgreSQL / PL/pgSQL conversion of the 16 Phase 2 SQL Server procedures.
-- All functions return one JSONB value per result row. Call with SELECT * FROM public.usp_name(...).
-- Idempotent schema creation; preserve existing data when rerun.

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS public.app_user (
  user_id uuid PRIMARY KEY,
  email varchar(320) NOT NULL UNIQUE,
  display_name varchar(200) NOT NULL,
  role varchar(20) NOT NULL CHECK (role IN ('Administrador','Viewer')),
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  password_hash varchar(255),
  activated_at timestamptz,
  auth_version integer NOT NULL DEFAULT 0
);
UPDATE public.app_user SET activated_at=created_at WHERE is_active AND activated_at IS NULL;

CREATE TABLE IF NOT EXISTS public.user_invitation (
  invitation_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES public.app_user(user_id),
  token_hash bytea NOT NULL UNIQUE CHECK(octet_length(token_hash)=32),
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  accepted_at timestamptz,
  revoked_at timestamptz
);
CREATE TABLE IF NOT EXISTS public.password_reset_token (
  reset_token_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES public.app_user(user_id),
  token_hash bytea NOT NULL UNIQUE CHECK(octet_length(token_hash)=32),
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  used_at timestamptz,
  revoked_at timestamptz
);
CREATE TABLE IF NOT EXISTS public.email_outbox (
  outbox_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid REFERENCES public.app_user(user_id),
  message_type varchar(40) NOT NULL,
  payload_encrypted text NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'Pending' CHECK(status IN ('Pending','Sending','Sent','Failed')),
  attempt_count integer NOT NULL DEFAULT 0,
  next_attempt_at timestamptz NOT NULL DEFAULT now(),
  last_attempt_at timestamptz,
  sent_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  last_error_code varchar(80)
);
CREATE INDEX IF NOT EXISTS ix_email_outbox_queue ON public.email_outbox(status,next_attempt_at,created_at);
CREATE TABLE IF NOT EXISTS public.audit_log (
  audit_log_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_user_id uuid REFERENCES public.app_user(user_id),
  target_user_id uuid REFERENCES public.app_user(user_id),
  action varchar(80) NOT NULL,
  details varchar(2000),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.business (
  business_id uuid PRIMARY KEY,
  name varchar(200) NOT NULL,
  description varchar(1000),
  status varchar(20) NOT NULL DEFAULT 'Active',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.social_platform (
  social_platform_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code varchar(30) NOT NULL UNIQUE,
  name varchar(80) NOT NULL,
  is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS public.external_connection (
  external_connection_id uuid PRIMARY KEY,
  provider varchar(40) NOT NULL,
  external_account_id varchar(255),
  status varchar(20) NOT NULL,
  connected_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.external_identity (
  external_identity_id uuid PRIMARY KEY,
  provider varchar(40) NOT NULL,
  external_subject varchar(255) NOT NULL,
  user_id uuid NOT NULL REFERENCES public.app_user(user_id),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(provider,external_subject)
);
CREATE TABLE IF NOT EXISTS public.social_account (
  social_account_id uuid PRIMARY KEY,
  business_id uuid NOT NULL REFERENCES public.business(business_id),
  social_platform_id integer NOT NULL REFERENCES public.social_platform(social_platform_id),
  external_connection_id uuid REFERENCES public.external_connection(external_connection_id),
  external_account_id varchar(255) NOT NULL,
  name varchar(200) NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'Disconnected',
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(social_platform_id,external_account_id)
);
CREATE TABLE IF NOT EXISTS public.user_business_platform_permission (
  permission_id uuid PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.app_user(user_id),
  business_id uuid NOT NULL REFERENCES public.business(business_id),
  social_platform_id integer NOT NULL REFERENCES public.social_platform(social_platform_id),
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid NOT NULL REFERENCES public.app_user(user_id),
  UNIQUE(user_id,business_id,social_platform_id)
);
INSERT INTO public.social_platform(code,name) VALUES ('facebook','Facebook'),('instagram','Instagram'),('tiktok','TikTok')
ON CONFLICT(code) DO NOTHING;
CREATE TABLE IF NOT EXISTS public.auth_session (
  session_id uuid PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.app_user(user_id),
  refresh_token_hash bytea NOT NULL UNIQUE CHECK(octet_length(refresh_token_hash)=32),
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  last_used_at timestamptz,
  revoked_at timestamptz
);
CREATE TABLE IF NOT EXISTS public.auth_session_token_history (
  token_hash bytea PRIMARY KEY CHECK(octet_length(token_hash)=32),
  session_id uuid NOT NULL REFERENCES public.auth_session(session_id),
  used_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_auth_session_user_active ON public.auth_session(user_id,revoked_at,expires_at);

-- 1. usp_Auth_GetActiveUser
CREATE OR REPLACE FUNCTION public.usp_auth_getactiveuser(p_userid uuid,p_sessionid uuid)
RETURNS SETOF jsonb LANGUAGE sql STABLE AS $$
 SELECT jsonb_build_object('UserId',u.user_id,'Email',u.email,'DisplayName',u.display_name,'Role',u.role,'AuthVersion',u.auth_version)
 FROM public.app_user u JOIN public.auth_session s ON s.user_id=u.user_id
 WHERE u.user_id=p_userid AND u.is_active AND s.session_id=p_sessionid AND s.revoked_at IS NULL AND s.expires_at>now()
$$;

-- 2. usp_Auth_FindByEmail
CREATE OR REPLACE FUNCTION public.usp_auth_findbyemail(p_email varchar(320))
RETURNS SETOF jsonb LANGUAGE sql STABLE AS $$
